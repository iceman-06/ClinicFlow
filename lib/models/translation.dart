  static String get(AppLanguage lang, String key, List<String>? replacements) {
    String text = _translations[lang]?[key] ?? _translations[AppLanguage.english]?[key] ?? key;
    if (replacements != null) {
      for (String s in replacements) {
        text = text.replaceFirst('%r', s);
      }
    }
    return text;
  }

  static String translateStatus(AppLanguage lang, String status) {
    switch (status) {
      case 'Upcoming':
        return get(lang, 'status_upcoming', null);
      case 'Confirmed':
        return get(lang, 'status_confirmed', null);
      case 'Checked in':
        return get(lang, 'status_checked_in', null);
      case 'Expected':
        return get(lang, 'status_expected', null);
      case 'In progress':
        return get(lang, 'status_in_progress', null);
      case 'No-show':
        return get(lang, 'status_no_show', null);
      case 'Done':
        return get(lang, 'status_done', null);
      case 'Cancelled':
        return get(lang, 'status_cancelled', null);
      default:
        return status;
    }
  }

